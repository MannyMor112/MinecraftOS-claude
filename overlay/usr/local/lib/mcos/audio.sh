#!/bin/bash
# Runs as root at boot. Braswell Chromebooks use the Intel SST/SOF DSP with a Realtek
# (rt5645/rt5650) or Maxim (max98090) codec; those need ALSA UCM to route audio to the
# speaker. No PulseAudio/PipeWire: Minecraft's OpenAL talks to ALSA directly.
. /usr/local/lib/mcos/common.sh
sleep 2
card=""
for c in /proc/asound/card[0-9]*; do
  [ -d "$c" ] || continue
  id=$(cat "$c/id"); n=${c##*card}
  case "$id" in HDMI|*hdmi*|*HDMI*|Intelhdmi*|*LPE*) continue ;; esac
  card=$n; break
done
[ -z "$card" ] && { echo "mcos-audio: no sound card found"; exit 0; }
name=$(cat /proc/asound/card$card/id)
echo "mcos-audio: using card $card ($name)"
# UCM: select the HiFi verb and the speaker; fall back gracefully
alsaucm -c "hw:$card" set _verb HiFi 2>/dev/null && alsaucm -c "hw:$card" set _enadev Speaker 2>/dev/null || true
alsactl init "$card" >/dev/null 2>&1 || true
for ctl in Master Speaker Headphone PCM 'Speaker Channel' 'Headphone Channel' 'DAC1'; do
  amixer -q -c "$card" sset "$ctl" 80% unmute 2>/dev/null || true
done
cat > /etc/asound.conf <<A
# generated by /usr/local/lib/mcos/audio.sh - software volume + mixing on card $card ($name)
pcm.!default { type plug; slave.pcm "mcosvol" }
pcm.mcosvol {
  type softvol
  slave.pcm "mcosdmix"
  control { name "MCOS Master"; card $card }
  min_dB -45.0
  max_dB 0.0
}
pcm.mcosdmix { type dmix; ipc_key 4242; ipc_perm 0666; slave { pcm "hw:$card,0"; period_size 1024; buffer_size 4096 } }
ctl.!default { type hw; card $card }
A
# create the softvol control and set it to 80 %
timeout 2 aplay -q -D default -t raw -f S16_LE -r 48000 -c 2 /dev/zero -d 1 2>/dev/null || true
amixer -q -c "$card" sset 'MCOS Master' 80% 2>/dev/null || true
echo "$card" > /run/mcos-audio-card
exit 0
